def _sha256_text(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def _skill_text(mode: str) -> str:
    content = files("voicemd").joinpath("resources/skill/SKILL.md").read_text(encoding="utf-8")
    if mode != "explicit":
        return content
    content = content.replace(
        "description: Apply the nearest VOICE.md communication contract when producing human-facing natural language, UI copy, messages, documents, reports, summaries, or spoken dialogue. Do not use for code, patches, tool calls/results, structured data, exact quotations, or raw machine output.",
        "description: Apply the nearest VOICE.md only when the user explicitly invokes this skill. Do not auto-activate for ordinary human-facing output.",
    )
    content = content.replace(
        "\n---\n\n<!-- Generated by VoiceMD -->",
        "\ndisable-model-invocation: true\n---\n\n<!-- Generated by VoiceMD -->",
        1,
    )
    content = content.replace(
        "Use this skill only when the requested output is primarily for a human to read or hear.",
        "Use this skill only after explicit harness-native invocation. In Codex use "
        "`$voice-contract`; in Claude Code, GitHub Copilot CLI, or Cursor use `/voice-contract`.",
    )
    content = content.replace(
        "Activate for chat answers, explanations, emails, messages, reports, documentation prose, UI copy, scripts, and spoken dialogue. Also activate when the user explicitly requests `@voice` or `voice:on`.",
        "Activate only after explicit invocation of this skill. Do not auto-activate solely because "
        "the output is chat, prose, UI copy, a document, or spoken dialogue. Portable `@voice` and "
        "`voice:on` markers are requests, but they cannot load a skill that the harness hides from "
        "model invocation.",
    )
    required = ("disable-model-invocation: true", "Do not auto-activate", "$voice-contract")
    if any(fragment not in content for fragment in required):
        raise InstallError("Could not render explicit-mode Agent Skill from the packaged template")
    return content


