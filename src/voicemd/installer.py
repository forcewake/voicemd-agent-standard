def _managed_block(text: str) -> str:
    return f"{MANAGED_START}\n## VOICE.md communication contract\n\n{text}\n{MANAGED_END}"


def _marker_span(text: str, *, path: Path) -> tuple[int, int] | None:
    starts = text.count(MANAGED_START)
    ends = text.count(MANAGED_END)
    if starts == 0 and ends == 0:
        return None
    if starts != 1 or ends != 1:
        raise InstallError(f"Invalid VoiceMD managed markers in {path}")
    start = text.find(MANAGED_START)
    end = text.find(MANAGED_END)
    if end < start:
        raise InstallError(f"Unbalanced VoiceMD managed markers in {path}")
    return start, end + len(MANAGED_END)


def _extract_managed_block(text: str, *, path: Path) -> str | None:
    span = _marker_span(text, path=path)
    return text[span[0] : span[1]] if span else None


def _render_injected(old: str, block: str, *, path: Path) -> str:
    span = _marker_span(old, path=path)
    if span:
        start, end = span
        new = old[:start].rstrip() + ("\n\n" if old[:start].strip() else "") + block
        if old[end:].strip():
            new += "\n\n" + old[end:].lstrip()
        return new + "\n"
    new = old.rstrip()
    if new:
        new += "\n\n"
    return new + block + "\n"


def _render_removed(old: str, *, path: Path) -> str | None:
    span = _marker_span(old, path=path)
    if not span:
        return old
    start, end = span
    new = (old[:start].rstrip() + "\n\n" + old[end:].lstrip()).strip()
    return new + "\n" if new else None


def _reject_direct_symlink(path: Path) -> None:
    if path.is_symlink():
        raise InstallError(f"Refusing to operate on symlink: {path}")


def inject_managed_block(path: Path, block: str, *, dry_run: bool = False) -> str:
    """Compatibility helper for one file; the installer uses a full transaction."""
    _reject_direct_symlink(path)
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    new = _render_injected(old, block, path=path)
    if not dry_run:
        _commit_changes(path.parent.resolve(), [_Change(path, new.encode("utf-8"), "updated")])
    return "updated" if old else "created"


def remove_managed_block(path: Path, *, dry_run: bool = False) -> str:
    """Compatibility helper for one file; preserves files without a managed block."""
    _reject_direct_symlink(path)
    if not path.exists():
        return "absent"
    old = path.read_text(encoding="utf-8")
    if _marker_span(old, path=path) is None:
        return "unmanaged"
    new = _render_removed(old, path=path)
    if not dry_run:
        _commit_changes(
            path.parent.resolve(),
            [_Change(path, new.encode("utf-8") if new is not None else None, "removed")],
        )
    return "removed"


def _targets(requested: Iterable[str]) -> list[str]:
    values = list(requested)
    if not values or "all" in values:
        return sorted(TARGETS)
    unknown = sorted(set(values) - TARGETS)
    if unknown:
        raise InstallError("Unknown install target(s): " + ", ".join(unknown))
    return sorted(set(values))


def _resolve_root(root: Path) -> Path:
    try:
        resolved = root.resolve(strict=True)
    except OSError as exc:
        raise InstallError(f"Install root does not exist: {root}: {exc}") from exc
    if not resolved.is_dir():
        raise InstallError(f"Install root is not a directory: {resolved}")
    return resolved


def _safe_path(root: Path, relative: Path) -> Path:
    if relative.is_absolute() or ".." in relative.parts:
        raise InstallError(f"Unsafe installer path: {relative}")
    path = root / relative
    current = root
    for index, part in enumerate(relative.parts):
        current = current / part
        if current.is_symlink():
            raise InstallError(f"Refusing to follow symlink inside install root: {current}")
        if not current.exists():
            continue
        is_last = index == len(relative.parts) - 1
        if is_last and not current.is_file():
            raise InstallError(f"Installer target is not a regular file: {current}")
        if not is_last and not current.is_dir():
            raise InstallError(f"Installer parent is not a directory: {current}")
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise InstallError(f"Installer path escapes root: {path}") from exc
    return path


def _empty_state() -> dict[str, Any]:
    return {"managed_by": STATE_OWNER, "version": STATE_VERSION, "targets": {}, "artifacts": {}}


def _load_state(root: Path) -> tuple[dict[str, Any], bool]:
    path = _safe_path(root, STATE_RELATIVE)
    if not path.exists():
        return _empty_state(), False
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise InstallError(f"Invalid VoiceMD install state: {path}: {exc}") from exc
    if not isinstance(state, dict) or state.get("managed_by") != STATE_OWNER:
        raise InstallError(f"Refusing to modify unmanaged install state: {path}")
    version = state.get("version", 1)
    if version not in {1, STATE_VERSION}:
        raise InstallError(f"Unsupported VoiceMD install state version {version}: {path}")
    targets = state.get("targets")
    if not isinstance(targets, dict):
        raise InstallError(f"Invalid targets in VoiceMD install state: {path}")
    for target, entry in targets.items():
        if target not in TARGETS or not isinstance(entry, dict):
            raise InstallError(f"Invalid target entry in VoiceMD install state: {target}")
        if entry.get("mode") not in {"auto", "always", "explicit"}:
            raise InstallError(f"Invalid mode for target {target} in VoiceMD install state")
    artifacts = state.get("artifacts", {})
    if not isinstance(artifacts, dict):
        raise InstallError(f"Invalid artifacts in VoiceMD install state: {path}")
    for relative, entry in artifacts.items():
        if not isinstance(relative, str) or not isinstance(entry, dict):
            raise InstallError(f"Invalid artifact entry in VoiceMD install state: {relative!r}")
        if entry.get("kind") not in {"generated", "managed_block"}:
            raise InstallError(f"Invalid artifact kind in VoiceMD install state: {relative}")
        digest = entry.get("sha256")
        owners = entry.get("owners")
        relative_path = Path(relative)
        expected_kind = "managed_block" if relative_path in MANAGED_ARTIFACT_PATHS else "generated"
        if relative_path not in ARTIFACT_OWNERS:
            raise InstallError(f"Unknown artifact in VoiceMD install state: {relative}")
        if entry.get("kind") != expected_kind:
            raise InstallError(f"Incorrect artifact kind in VoiceMD install state: {relative}")
        if (
            not isinstance(digest, str)
            or len(digest) != 64
            or any(character not in "0123456789abcdef" for character in digest)
            or not isinstance(owners, list)
            or any(not isinstance(owner, str) for owner in owners)
            or not set(owners) <= ARTIFACT_OWNERS[relative_path]
        ):
            raise InstallError(f"Invalid artifact ownership in VoiceMD install state: {relative}")
        _safe_path(root, relative_path)
    normalized = dict(state)
    normalized["version"] = STATE_VERSION
    normalized["targets"] = {key: dict(value) for key, value in targets.items()}
    normalized["artifacts"] = {key: dict(value) for key, value in artifacts.items()}
    return normalized, True


def _target_modes(target_state: dict[str, Any], owners: set[str]) -> dict[str, str]:
    return {
        owner: target_state[owner]["mode"]
        for owner in sorted(owners)
        if owner in target_state
    }


def _validate_shared_modes(target_state: dict[str, Any]) -> None:
    shared = _target_modes(target_state, SHARED_SKILL_OWNERS)
    classes = {"explicit" if mode == "explicit" else "implicit" for mode in shared.values()}
    if len(classes) > 1:
        detail = ", ".join(f"{owner}={mode}" for owner, mode in shared.items())
        raise InstallError(
            "Incompatible modes for the shared .agents voice-contract skill. "
            "Explicit owners cannot share it with auto/always owners: " + detail
        )
    agents = _target_modes(target_state, AGENTS_BOOTSTRAP_OWNERS)
    implicit_modes = {mode for mode in agents.values() if mode != "explicit"}
    if len(implicit_modes) > 1:
        detail = ", ".join(f"{owner}={mode}" for owner, mode in agents.items())
        raise InstallError(
            "Incompatible modes for the shared AGENTS.md bootstrap. "
            "Its owners must use the same auto/always mode: " + detail
        )


