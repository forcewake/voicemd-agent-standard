def _metadata(artifact: _Artifact) -> dict[str, Any]:
    return {
        "kind": artifact.kind,
        "owners": sorted(artifact.owners),
        "sha256": _sha256_text(artifact.content),
    }


def _owned_hash(state: dict[str, Any], relative: Path, kind: ArtifactKind) -> str | None:
    entry = state.get("artifacts", {}).get(relative.as_posix())
    if not isinstance(entry, dict) or entry.get("kind") != kind:
        return None
    digest = entry.get("sha256")
    return digest if isinstance(digest, str) else None


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise InstallError(f"Cannot inspect installer artifact {path}: {exc}") from exc


def _plan_generated(
    path: Path,
    relative: Path,
    desired: _Artifact | None,
    state: dict[str, Any],
    *,
    operation: Literal["install", "uninstall"],
) -> tuple[_Change | None, str | None]:
    if not path.exists():
        if desired is None:
            return None, None
        return _Change(path, desired.content.encode("utf-8"), "created"), "created"

    current = _read_text(path)
    current_hash = _sha256_text(current)
    owned_hash = _owned_hash(state, relative, "generated")
    known = current in _known_generated_contents(relative)

    if desired is not None:
        if owned_hash is not None and current_hash != owned_hash:
            raise InstallError(f"Refusing to overwrite modified managed file: {path}")
        if owned_hash is None and not known and current != desired.content:
            raise InstallError(f"Refusing to overwrite unowned file: {path}")
        if current == desired.content:
            return None, "unchanged"
        return _Change(path, desired.content.encode("utf-8"), "updated"), "updated"

    if owned_hash is not None:
        if current_hash != owned_hash:
            if operation == "install":
                raise InstallError(f"Cannot remove modified managed file during mode change: {path}")
            return None, "modified-retained"
        return _Change(path, None, "removed"), "removed"
    if known:
        return _Change(path, None, "removed"), "removed"
    return None, "unmanaged"


def _plan_managed(
    path: Path,
    relative: Path,
    desired: _Artifact | None,
    state: dict[str, Any],
    *,
    operation: Literal["install", "uninstall"],
) -> tuple[_Change | None, str | None]:
    old = _read_text(path) if path.exists() else ""
    block = _extract_managed_block(old, path=path)
    owned_hash = _owned_hash(state, relative, "managed_block")
    known = block in _known_managed_blocks() if block is not None else False

    if desired is not None:
        if block is not None:
            actual_hash = _sha256_text(block)
            if owned_hash is not None and actual_hash != owned_hash:
                raise InstallError(f"Refusing to overwrite modified managed block: {path}")
            if owned_hash is None and not known and block != desired.content:
                raise InstallError(f"Refusing to overwrite unowned VoiceMD block: {path}")
        new = _render_injected(old, desired.content, path=path)
        if new == old:
            return None, "unchanged"
        status = "created" if not path.exists() else "updated"
        return _Change(path, new.encode("utf-8"), status), status

    if block is None:
        return None, "unmanaged" if path.exists() else None
    actual_hash = _sha256_text(block)
    if owned_hash is not None and actual_hash != owned_hash:
        if operation == "install":
            raise InstallError(f"Cannot remove modified managed block during mode change: {path}")
        return None, "modified-retained"
    if owned_hash is None and not known:
        if operation == "install":
            raise InstallError(f"Cannot remove unowned VoiceMD block during mode change: {path}")
        return None, "unmanaged"
    new = _render_removed(old, path=path)
    return (
        _Change(path, new.encode("utf-8") if new is not None else None, "removed"),
        "removed",
    )


def _affected_paths(selected: set[str], state: dict[str, Any]) -> set[Path]:
    affected = {
        relative for relative, owners in ARTIFACT_OWNERS.items() if selected & owners
    }
    for relative, entry in state.get("artifacts", {}).items():
        owners = entry.get("owners", []) if isinstance(entry, dict) else []
        if selected & set(owners):
            affected.add(Path(relative))
    return affected


def _state_change(
    root: Path,
    state: dict[str, Any],
    *,
    existed: bool,
) -> tuple[_Change | None, tuple[Path, str] | None]:
    path = _safe_path(root, STATE_RELATIVE)
    targets = state.get("targets", {})
    artifacts = state.get("artifacts", {})
    if not targets and not artifacts:
        if not path.exists():
            return None, None
        return _Change(path, None, "removed"), (path, "removed")
    content = (json.dumps(state, indent=2, sort_keys=True) + "\n").encode("utf-8")
    if path.exists() and path.read_bytes() == content:
        return None, (path, "unchanged")
    status = "updated" if existed or path.exists() else "created"
    return _Change(path, content, status), (path, status)


def _mkdir_parents(path: Path, root: Path, created: list[Path]) -> None:
    missing: list[Path] = []
    parent = path.parent
    while parent != root and not parent.exists():
        missing.append(parent)
        parent = parent.parent
    for directory in reversed(missing):
        if directory.is_symlink():
            raise InstallError(f"Refusing to create through symlink: {directory}")
        directory.mkdir()
        created.append(directory)


def _replace_bytes(path: Path, content: bytes, mode: int | None = None) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix=".voicemd-", dir=path.parent)
    temporary_path = Path(temporary)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary_path, mode if mode is not None else 0o644)
        os.replace(temporary_path, path)
    finally:
        if temporary_path.exists():
            temporary_path.unlink()


def _snapshot(path: Path) -> _Snapshot:
    if not path.exists():
        return _Snapshot(path, False, b"", None)
    details = path.stat()
    return _Snapshot(path, True, path.read_bytes(), stat.S_IMODE(details.st_mode))


def _commit_changes(root: Path, changes: list[_Change]) -> None:
    if not changes:
        return
    snapshots = [_snapshot(change.path) for change in changes]
    created_directories: list[Path] = []
    applied = 0
    try:
        for change, snapshot in zip(changes, snapshots):
            relative = change.path.relative_to(root)
            _safe_path(root, relative)
            if change.content is None:
                if change.path.exists():
                    change.path.unlink()
            else:
                _mkdir_parents(change.path, root, created_directories)
                _safe_path(root, relative)
                _replace_bytes(change.path, change.content, snapshot.mode)
            applied += 1
    except Exception as exc:
        rollback_errors: list[str] = []
        for snapshot in reversed(snapshots[:applied]):
            try:
                if snapshot.existed:
                    _mkdir_parents(snapshot.path, root, created_directories)
                    _replace_bytes(snapshot.path, snapshot.content, snapshot.mode)
                elif snapshot.path.exists() or snapshot.path.is_symlink():
                    snapshot.path.unlink()
            except Exception as rollback_exc:  # noqa: BLE001  # pragma: no cover
                rollback_errors.append(f"{snapshot.path}: {rollback_exc}")
        for directory in reversed(created_directories):
            try:
                directory.rmdir()
            except OSError:
                pass
        detail = f"; rollback errors: {'; '.join(rollback_errors)}" if rollback_errors else ""
        raise InstallError(f"Installer transaction failed and was rolled back: {exc}{detail}") from exc
    for change in changes:
        if change.content is not None:
            continue
        parent = change.path.parent
        while parent != root and root in parent.parents:
            try:
                parent.rmdir()
            except OSError:
                break
            parent = parent.parent


def _reconcile(
    root: Path,
    state: dict[str, Any],
    *,
    selected: set[str],
    desired: dict[Path, _Artifact],
    state_existed: bool,
    operation: Literal["install", "uninstall"],
    dry_run: bool,
) -> list[tuple[Path, str]]:
    changes: list[_Change] = []
    results: list[tuple[Path, str]] = []
    affected = _affected_paths(selected, state)
    artifacts_state = dict(state.get("artifacts", {}))

    for relative in sorted(affected, key=lambda item: item.as_posix()):
        path = _safe_path(root, relative)
        artifact = desired.get(relative)
        kind: ArtifactKind
        if artifact is not None:
            kind = artifact.kind
        else:
            entry = artifacts_state.get(relative.as_posix(), {})
            if isinstance(entry, dict) and entry.get("kind") in {"generated", "managed_block"}:
                kind = entry["kind"]
            else:
                kind = "managed_block" if relative in MANAGED_ARTIFACT_PATHS else "generated"
        if kind == "generated":
            change, status = _plan_generated(
                path, relative, artifact, state, operation=operation
            )
        else:
            change, status = _plan_managed(
                path, relative, artifact, state, operation=operation
            )
        if change is not None:
            changes.append(change)
        if status is not None and not (status == "unmanaged" and artifact is None):
            results.append((path, status))
        artifacts_state.pop(relative.as_posix(), None)
        if artifact is not None:
            artifacts_state[relative.as_posix()] = _metadata(artifact)

    state["artifacts"] = artifacts_state
    state["version"] = STATE_VERSION
    state_change, state_result = _state_change(root, state, existed=state_existed)
    if state_change is not None:
        changes.append(state_change)
    if state_result is not None:
        results.append(state_result)

    # All paths, markers, ownership hashes, and shared-mode constraints have
    # passed preflight. Only this point may mutate the filesystem.
    if not dry_run:
        _commit_changes(root, changes)
    return results


def adapter_health(root: Path) -> dict[str, Any]:
    """Inspect installer state and owned artifact content without changing files."""
    report: dict[str, Any] = {
        "ok": True,
        "state": "absent",
        "version": None,
        "targets": {},
        "artifacts": [],
        "issues": [],
    }
    try:
        root = _resolve_root(root)
        state, state_existed = _load_state(root)
        report["state"] = "managed" if state_existed else "absent"
        report["version"] = state["version"] if state_existed else None
        report["targets"] = state["targets"]
        _validate_shared_modes(state["targets"])
        desired = _desired_artifacts(root, state["targets"])
    except InstallError as exc:
        report["ok"] = False
        report["state"] = "invalid"
        report["issues"].append(str(exc))
        return report

    tracked = {Path(value) for value in state.get("artifacts", {})}
    inspected = set(desired) | tracked
    for relative in ARTIFACT_OWNERS:
        try:
            candidate = _safe_path(root, relative)
        except InstallError as exc:
            report["ok"] = False
            report["issues"].append(str(exc))
            continue
        if candidate.exists() or candidate.is_symlink():
            inspected.add(relative)

    for relative in sorted(inspected, key=lambda value: value.as_posix()):
        entry: dict[str, Any] = {"path": relative.as_posix()}
        metadata = state.get("artifacts", {}).get(relative.as_posix())
        artifact = desired.get(relative)
        if isinstance(metadata, dict):
            kind = metadata.get("kind")
            entry["kind"] = kind
            entry["owners"] = metadata.get("owners", [])
            entry["expected_sha256"] = metadata.get("sha256")
        elif artifact is not None:
            kind = artifact.kind
            entry["kind"] = kind
            entry["owners"] = sorted(artifact.owners)
            entry["expected_sha256"] = _sha256_text(artifact.content)
        else:
            kind = "managed_block" if relative in MANAGED_ARTIFACT_PATHS else "generated"
            entry["kind"] = kind
            entry["owners"] = []

        try:
            path = _safe_path(root, relative)
            if not path.exists():
                status = "missing" if artifact is not None or metadata is not None else "absent"
            elif kind == "managed_block":
                block = _extract_managed_block(_read_text(path), path=path)
                if block is None:
                    status = "missing-block" if artifact is not None or metadata is not None else "unmanaged"
                else:
                    entry["actual_sha256"] = _sha256_text(block)
                    if metadata is None:
                        status = (
                            "known-untracked"
                            if block in _known_managed_blocks()
                            else "untracked-managed-marker"
                        )
                    elif entry["actual_sha256"] != entry["expected_sha256"]:
                        status = "modified"
                    elif artifact is None:
                        status = "orphaned-state"
                    elif _sha256_text(artifact.content) != entry["expected_sha256"]:
                        status = "stale"
                    else:
                        status = "ok"
            else:
                content = _read_text(path)
                entry["actual_sha256"] = _sha256_text(content)
                entry["marker"] = GENERATED_MARKER in content
                if metadata is None:
                    if content in _known_generated_contents(relative):
                        status = "known-untracked"
                    else:
                        status = "untracked-generated-marker" if entry["marker"] else "unmanaged"
                elif entry["actual_sha256"] != entry["expected_sha256"]:
                    status = "modified"
                elif artifact is None:
                    status = "orphaned-state"
                elif _sha256_text(artifact.content) != entry["expected_sha256"]:
                    status = "stale"
                elif not entry["marker"]:
                    status = "missing-marker"
                else:
                    status = "ok"
        except InstallError as exc:
            status = "invalid"
            entry["error"] = str(exc)

        entry["status"] = status
        if status not in {"ok", "absent", "unmanaged", "known-untracked"}:
            report["ok"] = False
            report["issues"].append(f"{relative.as_posix()}: {status}")
        report["artifacts"].append(entry)
    return report


def install(
    root: Path,
    *,
    targets: Iterable[str] = ("all",),
    mode: str = "auto",
    dry_run: bool = False,
) -> list[tuple[Path, str]]:
    if mode not in {"auto", "always", "explicit"}:
        raise InstallError("mode must be auto, always, or explicit")
    root = _resolve_root(root)
    selected_list = _targets(targets)
    selected = set(selected_list)
    state, state_existed = _load_state(root)
    target_state = state["targets"]
    for target in selected_list:
        target_state[target] = {"mode": mode}
    _validate_shared_modes(target_state)
    desired = _desired_artifacts(root, target_state)

    if "aider" in selected:
        warnings.warn(
            "Aider does not auto-discover .aider.voice.yml; activate it with "
            "`aider --config .aider.voice.yml`. The requested mode cannot make that file "
            "automatic by itself.",
            InstallWarning,
            stacklevel=2,
        )
    return _reconcile(
        root,
        state,
        selected=selected,
        desired=desired,
        state_existed=state_existed,
        operation="install",
        dry_run=dry_run,
    )


def uninstall(
    root: Path,
    *,
    targets: Iterable[str] = ("all",),
    dry_run: bool = False,
) -> list[tuple[Path, str]]:
    root = _resolve_root(root)
    selected = set(_targets(targets))
    state, state_existed = _load_state(root)
    target_state = state["targets"]
    for target in selected:
        target_state.pop(target, None)
    _validate_shared_modes(target_state)
    desired = _desired_artifacts(root, target_state)
    return _reconcile(
        root,
        state,
        selected=selected,
        desired=desired,
        state_existed=state_existed,
        operation="uninstall",
        dry_run=dry_run,
    )
