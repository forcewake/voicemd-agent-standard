def _desired_artifacts(root: Path, target_state: dict[str, Any]) -> dict[Path, _Artifact]:
    del root  # Reserved for future root-specific adapter rendering.
    desired: dict[Path, _Artifact] = {}

    shared_modes = _target_modes(target_state, SHARED_SKILL_OWNERS)
    if shared_modes:
        shared_mode = "explicit" if set(shared_modes.values()) == {"explicit"} else "auto"
        desired[SHARED_SKILL_RELATIVE] = _Artifact(
            SHARED_SKILL_RELATIVE,
            "generated",
            _skill_text(shared_mode),
            frozenset(shared_modes),
        )
    if target_state.get("codex", {}).get("mode") == "explicit":
        desired[CODEX_POLICY_RELATIVE] = _Artifact(
            CODEX_POLICY_RELATIVE,
            "generated",
            _codex_policy_text(),
            frozenset({"codex"}),
        )

    agents_modes = _target_modes(target_state, AGENTS_BOOTSTRAP_OWNERS)
    agents_owners = {owner for owner, mode in agents_modes.items() if mode != "explicit"}
    if agents_owners:
        agents_mode = next(iter({agents_modes[owner] for owner in agents_owners}))
        text = AUTO_TEXT if agents_mode == "auto" else ALWAYS_TEXT
