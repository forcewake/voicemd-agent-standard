def _known_generated_contents(relative: Path) -> set[str]:
    skill_paths = {
        SHARED_SKILL_RELATIVE,
        CLAUDE_SKILL_RELATIVE,
        CLINE_SKILL_RELATIVE,
        CURSOR_SKILL_RELATIVE,
    }
    if relative in skill_paths:
        return {_skill_text("auto"), _skill_text("explicit"), _legacy_explicit_skill_text()}
    if relative == CODEX_POLICY_RELATIVE:
        return {_codex_policy_text()}
    if relative == Path(".cursor/rules/voice-contract.mdc"):
        legacy_cursor = _cursor_rule_text("explicit").replace(EXPLICIT_TEXT, LEGACY_EXPLICIT_TEXT)
        return {
            *(_cursor_rule_text(mode) for mode in ("auto", "always", "explicit")),
            legacy_cursor,
        }
    if relative in {Path(".clinerules/voice-contract.md"), Path(".windsurf/rules/voice-contract.md")}:
        return {
            _rule_text(text)
            for text in (AUTO_TEXT, ALWAYS_TEXT, EXPLICIT_TEXT, LEGACY_EXPLICIT_TEXT)
        }
    if relative == Path(".aider.voice.yml"):
        return {
            "# Generated by VoiceMD\n# Start Aider with: aider --config .aider.voice.yml\nread:\n  - VOICE.md\n",
            "# Generated by VoiceMD\nread:\n  - VOICE.md\n",
            *(_aider_text(mode) for mode in ("auto", "always", "explicit")),
        }
    return set()


